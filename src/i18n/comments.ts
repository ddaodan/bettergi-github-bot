import type {
  AiHelpResult,
  CommentMode,
  DuplicateCandidate,
  FixSuggestionResult,
  SimilarIssueCandidate
} from "../core/types.js";

const zhAiNote = "> 注：以上内容由 AI 生成，仅供参考，请结合项目文档、代码和维护者意见进一步确认。";
const enAiNote = "> Note: This response was generated by AI for reference only. Please verify it against the project docs, code, and maintainer guidance.";

type AiCommentLayout = {
  titleZh: string;
  titleEn: string;
  summaryZh?: string;
  summaryEn?: string;
  analysisZh: string;
  analysisEn: string;
  actionZh: string;
  actionEn: string;
  missingZh: string;
  missingEn: string;
};

const AI_ANALYSIS_ITEM_LIMIT = 3;
const AI_ACTION_ITEM_LIMIT = 5;
const AI_MISSING_ITEM_LIMIT = 3;

function renderSimilarIssueEntries(mode: "zh" | "en", issues: SimilarIssueCandidate[]): string[] {
  return issues.map((entry) => {
    const label = mode === "zh" ? "相似度" : "Score";
    return `#${entry.candidate.number} | ${label}：${entry.score.toFixed(2)}`;
  });
}

function renderSimilarIssuesSection(params: {
  mode: "zh" | "en";
  issues: SimilarIssueCandidate[];
}): string {
  const lines = renderSimilarIssueEntries(params.mode, params.issues);

  if (params.mode === "zh") {
    return [
      "## 可能相关的历史 Issue",
      "",
      "<details>",
      `<summary>展开查看 ${params.issues.length} 个相关 Issue</summary>`,
      "",
      ...lines,
      "",
      "</details>"
    ].join("\n");
  }

  return [
    "## Possibly Related Issues",
    "",
    "<details>",
    `<summary>Expand to view ${params.issues.length} related issues</summary>`,
    "",
    ...lines,
    "",
    "</details>"
  ].join("\n");
}

function bilingual(mode: CommentMode, zh: string, en: string): string {
  if (mode === "zh") {
    return zh;
  }

  return `${zh}\n\n---\n\n${en}`;
}

function renderList(items: string[], emptyLabel: string): string[] {
  if (items.length === 0) {
    return [`- ${emptyLabel}`];
  }

  return items.map((item) => `- ${item}`);
}

function renderOptionalAiListSection(title: string, items: string[], limit: number): string | undefined {
  const visibleItems = items.map((item) => item.trim()).filter(Boolean).slice(0, limit);
  if (visibleItems.length === 0) {
    return undefined;
  }

  return [`### ${title}`, ...visibleItems.map((item) => `- ${item}`)].join("\n");
}

function renderOptionalAiSummary(title: string | undefined, value: string): string | undefined {
  const content = value.trim();
  return title && content ? `### ${title}\n${content}` : undefined;
}

function resolveLocalizedText(primary: string | undefined, fallback: string): string {
  const value = primary?.trim();
  return value ? value : fallback;
}

function resolveLocalizedList(primary: string[] | undefined, fallback: string[]): string[] {
  return (primary?.length ?? 0) > 0 ? primary! : fallback;
}

function renderCandidateFiles(
  items: FixSuggestionResult["candidateFiles"],
  emptyLabel: string,
  reasonSelector: (item: FixSuggestionResult["candidateFiles"][number]) => string | undefined = (item) => item.reason
): string[] {
  if (items.length === 0) {
    return [`- ${emptyLabel}`];
  }

  return items.map((item) => {
    const reason = resolveLocalizedText(reasonSelector(item), item.reason);
    return `- \`${item.path}\`${reason ? `：${reason}` : ""}`;
  });
}

function renderIssueState(mode: "zh" | "en", state: "open" | "closed"): string {
  if (mode === "zh") {
    return state === "open" ? "开放" : "已关闭";
  }

  return state;
}

function getAiCommentLayout(templateKey?: string): AiCommentLayout {
  switch (templateKey) {
    case "bug":
      return {
        titleZh: "AI 分析建议",
        titleEn: "AI Guidance",
        analysisZh: "可能原因",
        analysisEn: "Possible Causes",
        actionZh: "建议排查步骤",
        actionEn: "Suggested Troubleshooting Steps",
        missingZh: "仍需补充的信息",
        missingEn: "Additional Information Needed"
      };
    case "question":
      return {
        titleZh: "AI 参考回答",
        titleEn: "AI Reference Answer",
        summaryZh: "直接回答",
        summaryEn: "Direct Answer",
        analysisZh: "判断依据",
        analysisEn: "Key Points",
        actionZh: "建议下一步",
        actionEn: "Suggested Next Steps",
        missingZh: "如需进一步确认",
        missingEn: "If More Context Is Needed"
      };
    case "feature":
    case "suggestion":
      return {
        titleZh: "AI 方案建议",
        titleEn: "AI Proposal Suggestions",
        analysisZh: "可行思路",
        analysisEn: "Feasible Approaches",
        actionZh: "建议实施路径",
        actionEn: "Suggested Implementation Path",
        missingZh: "仍需确认的信息",
        missingEn: "Information To Confirm"
      };
    default:
      return {
        titleZh: "AI 参考建议",
        titleEn: "AI Reference Suggestions",
        analysisZh: "分析要点",
        analysisEn: "Key Analysis",
        actionZh: "建议处理方向",
        actionEn: "Suggested Next Actions",
        missingZh: "仍需补充的信息",
        missingEn: "Additional Information Needed"
      };
  }
}

export function renderValidationComment(params: {
  mode: CommentMode;
  valid: boolean;
  templateKey?: string;
  missingSections: string[];
  noTemplateDetected?: boolean;
  closedForInvalidTemplate?: boolean;
  transferred?: boolean;
  dryRun?: boolean;
}): string {
  const transferredNote = params.transferred
    ? bilingual(
      params.mode,
      "> 检测到本 Issue 由其他仓库转移而来，本次仅要求通用必填内容，仓库特有段落暂不强制。",
      "> This issue was detected as transferred from another repository. Only universal required sections are enforced; repository-specific sections are waived for now."
    )
    : undefined;

  if (params.valid) {
    return [
      bilingual(
        params.mode,
        `## 模板检查结果\n\n已通过模板检查。当前识别模板：\`${params.templateKey ?? "unknown"}\`。`,
        `## Template Check Result\n\nThe issue passed template validation. Detected template: \`${params.templateKey ?? "unknown"}\`.`
      ),
      transferredNote
    ].filter((part): part is string => Boolean(part)).join("\n\n");
  }

  const zhMissing = params.missingSections.map((item) => `- ${item}`).join("\n") || "- 暂无";
  const enMissing = params.missingSections.map((item) => `- ${item}`).join("\n") || "- None";

  if (params.noTemplateDetected) {
    if (params.closedForInvalidTemplate) {
      return [
        bilingual(
          params.mode,
          `## 模板检查结果\n\n未检测到 Issue 模板内容，${params.dryRun ? "计划自动关闭（当前为 dry-run，未实际修改 Issue 状态）" : "已自动关闭"}。\n\n请使用仓库提供的 Issue 模板提交，补全后会自动重新打开。`,
          `## Template Check Result\n\nNo issue template content was detected, so this issue ${params.dryRun ? "is marked for automatic closure (dry-run; the issue state was not changed)" : "was closed automatically"}.\n\nPlease submit using one of the repository's issue templates; it will be reopened automatically once completed.`
        ),
        transferredNote
      ].filter((part): part is string => Boolean(part)).join("\n\n");
    }

    return [
      bilingual(
        params.mode,
        "## 模板检查结果\n\n未检测到 Issue 模板内容。\n\n请使用仓库提供的 Issue 模板提交。",
        "## Template Check Result\n\nNo issue template content was detected.\n\nPlease submit using one of the repository's issue templates."
      ),
      transferredNote
    ].filter((part): part is string => Boolean(part)).join("\n\n");
  }

  if (params.closedForInvalidTemplate) {
    return [
      bilingual(
        params.mode,
        `## 模板检查结果\n\nIssue 未按模板填写或必填内容不完整，${params.dryRun ? "计划自动关闭（当前为 dry-run，未实际修改 Issue 状态）" : "已自动关闭"}。缺少的必填内容：\n${zhMissing}\n\n请按模板补全上述内容，补全并通过检查后将自动重新打开。`,
        `## Template Check Result\n\nThis issue was ${params.dryRun ? "marked for automatic closure (dry-run; the issue state was not changed)" : "closed automatically"} because it was not filled in according to the template or required sections are incomplete. Missing required sections:\n${enMissing}\n\nPlease complete the sections above according to the template. It will be reopened automatically once the template check passes.`
      ),
      transferredNote
    ].filter((part): part is string => Boolean(part)).join("\n\n");
  }

  return [
    bilingual(
      params.mode,
      `## 模板检查结果\n\nIssue 未通过模板检查，请补充以下必填内容：\n${zhMissing}`,
      `## Template Check Result\n\nThis issue did not pass template validation. Please complete the following required sections:\n${enMissing}`
    ),
    transferredNote
  ].filter((part): part is string => Boolean(part)).join("\n\n");
}

export function renderDuplicateComment(params: {
  mode: CommentMode;
  duplicateOf: DuplicateCandidate;
  confidence: number;
}): string {
  const issueRef = `#${params.duplicateOf.number}`;
  const zh = [
    issueRef,
    "",
    "## 重复 Issue 处理",
    "",
    `当前 Issue 已被判定为与 #${params.duplicateOf.number} 重复，已自动关闭。`,
    "",
    `- 置信度：${params.confidence.toFixed(2)}`
  ].join("\n");
  const en = [
    issueRef,
    "",
    "## Duplicate Issue Handling",
    "",
    `This issue was identified as a duplicate of #${params.duplicateOf.number} and has been closed automatically.`,
    "",
    `- Confidence: ${params.confidence.toFixed(2)}`
  ].join("\n");

  return params.mode === "zh" ? zh : `${zh}\n\n---\n\n${en}`;
}

export function renderSimilarIssuesComment(params: {
  mode: CommentMode;
  issues: SimilarIssueCandidate[];
}): string {
  const zh = renderSimilarIssuesSection({
    mode: "zh",
    issues: params.issues
  });

  if (params.mode === "zh") {
    return zh;
  }

  const en = renderSimilarIssuesSection({
    mode: "en",
    issues: params.issues
  });

  return `${zh}\n\n---\n\n${en}`;
}

export function renderAiHelpComment(params: {
  mode: CommentMode;
  templateKey?: string;
  help: AiHelpResult;
  relatedIssues?: SimilarIssueCandidate[];
}): string {
  const layout = getAiCommentLayout(params.templateKey);
  const zhSections = [
    params.relatedIssues && params.relatedIssues.length > 0
      ? renderSimilarIssuesSection({
        mode: "zh",
        issues: params.relatedIssues
      })
      : undefined,
    `## ${layout.titleZh}`,
    renderOptionalAiSummary(layout.summaryZh, params.help.summary),
    renderOptionalAiListSection(layout.analysisZh, params.help.possibleCauses, AI_ANALYSIS_ITEM_LIMIT),
    renderOptionalAiListSection(layout.actionZh, params.help.troubleshootingSteps, AI_ACTION_ITEM_LIMIT),
    renderOptionalAiListSection(layout.missingZh, params.help.missingInformation, AI_MISSING_ITEM_LIMIT),
    zhAiNote
  ].filter((section): section is string => Boolean(section));
  const zh = zhSections.join("\n\n");

  if (params.mode === "zh") {
    return zh;
  }

  const enSections = [
    params.relatedIssues && params.relatedIssues.length > 0
      ? renderSimilarIssuesSection({
        mode: "en",
        issues: params.relatedIssues
      })
      : undefined,
    `## ${layout.titleEn}`,
    renderOptionalAiSummary(layout.summaryEn, resolveLocalizedText(params.help.summaryEn, params.help.summary)),
    renderOptionalAiListSection(
      layout.analysisEn,
      resolveLocalizedList(params.help.possibleCausesEn, params.help.possibleCauses),
      AI_ANALYSIS_ITEM_LIMIT
    ),
    renderOptionalAiListSection(
      layout.actionEn,
      resolveLocalizedList(params.help.troubleshootingStepsEn, params.help.troubleshootingSteps),
      AI_ACTION_ITEM_LIMIT
    ),
    renderOptionalAiListSection(
      layout.missingEn,
      resolveLocalizedList(params.help.missingInformationEn, params.help.missingInformation),
      AI_MISSING_ITEM_LIMIT
    ),
    enAiNote
  ].filter((section): section is string => Boolean(section));
  const en = enSections.join("\n\n");

  return `${zh}\n\n---\n\n${en}`;
}

export function renderFixSuggestionComment(params: {
  mode: CommentMode;
  suggestion: FixSuggestionResult;
}): string {
  const patchDraft = params.suggestion.patchDraft.trim() || "# patch draft unavailable";
  const zh = [
    "## AI 修复建议",
    "",
    `### 问题判断\n${params.suggestion.summary}`,
    "",
    "### 候选修改文件",
    ...renderCandidateFiles(params.suggestion.candidateFiles, "暂无"),
    "",
    "### 修改建议",
    ...renderList(params.suggestion.changeSuggestions, "暂无"),
    "",
    "### 补丁草案",
    "```diff",
    patchDraft,
    "```",
    "",
    "### 验证建议",
    ...renderList(params.suggestion.verificationSteps, "暂无"),
    "",
    "### 风险提示",
    ...renderList(params.suggestion.risks, "暂无"),
    "",
    zhAiNote
  ].join("\n");

  if (params.mode === "zh") {
    return zh;
  }

  const en = [
    "## AI Fix Suggestion",
    "",
    `### Assessment\n${resolveLocalizedText(params.suggestion.summaryEn, params.suggestion.summary)}`,
    "",
    "### Candidate Files",
    ...renderCandidateFiles(params.suggestion.candidateFiles, "None", (item) => item.reasonEn),
    "",
    "### Change Suggestions",
    ...renderList(resolveLocalizedList(params.suggestion.changeSuggestionsEn, params.suggestion.changeSuggestions), "None"),
    "",
    "### Patch Draft",
    "```diff",
    patchDraft,
    "```",
    "",
    "### Verification Steps",
    ...renderList(resolveLocalizedList(params.suggestion.verificationStepsEn, params.suggestion.verificationSteps), "None"),
    "",
    "### Risks",
    ...renderList(resolveLocalizedList(params.suggestion.risksEn, params.suggestion.risks), "None"),
    "",
    enAiNote
  ].join("\n");

  return `${zh}\n\n---\n\n${en}`;
}

export function renderFixStatusComment(params: {
  mode: CommentMode;
  titleZh: string;
  titleEn: string;
  messageZh: string;
  messageEn: string;
}): string {
  return bilingual(
    params.mode,
    `## ${params.titleZh}\n\n${params.messageZh}`,
    `## ${params.titleEn}\n\n${params.messageEn}`
  );
}

export function renderPullRequestLocationComment(params: {
  mode: CommentMode;
  issues: Array<{ file: string; expectedLocation: string; reason: string }>;
}): string {
  const zhLines = params.issues
    .map((item) => `- \`${item.file}\` → ${item.reason}，建议移动到 \`${item.expectedLocation}\``)
    .join("\n");
  const enLines = params.issues
    .map((item) => `- \`${item.file}\` → ${item.reason}; please move it to \`${item.expectedLocation}\``)
    .join("\n");

  return bilingual(
    params.mode,
    [
      "## 提交位置检查",
      "",
      "以下文件看起来不在约定目录中，请确认是否需要调整（不影响合并，仅供参考）：",
      "",
      zhLines
    ].join("\n"),
    [
      "## File Placement Check",
      "",
      "The following files appear to be outside of their expected directories. This is advisory only and does not block merging:",
      "",
      enLines
    ].join("\n")
  );
}

export function renderPullRequestIssueLinkComment(params: {
  mode: CommentMode;
  linkedNumbers: number[];
  appendedKeywords: string[];
}): string {
  const zhAppended = params.appendedKeywords.length > 0
    ? `\n\n已自动在 PR 描述中补充关闭语句：\n${params.appendedKeywords.map((item) => `- \`${item}\``).join("\n")}`
    : "";
  const enAppended = params.appendedKeywords.length > 0
    ? `\n\nClosing statements were added to the pull request description:\n${params.appendedKeywords.map((item) => `- \`${item}\``).join("\n")}`
    : "";

  const zhRefs = params.linkedNumbers.map((number) => `#${number}`).join("、");
  const enRefs = params.linkedNumbers.map((number) => `#${number}`).join(", ");

  return bilingual(
    params.mode,
    [
      "## 关联 Issue 检查",
      "",
      `本 PR 关联了以下 Issue：${zhRefs}。`,
      "合并后 GitHub 会根据 PR 描述中的关闭语句自动关闭对应 Issue。",
      zhAppended
    ].join("\n"),
    [
      "## Related Issue Check",
      "",
      `This pull request references: ${enRefs}.`,
      "GitHub will close the related issues automatically after this pull request is merged.",
      enAppended
    ].join("\n")
  );
}

